namespace Melodee.Common.Enums.PartyMode;

/// <summary>
/// Represents a playback intent action.
/// </summary>
public enum PlaybackIntent
{
    /// <summary>
    /// Start playback.
    /// </summary>
    Play,

    /// <summary>
    /// Pause playback.
    /// </summary>
    Pause,

    /// <summary>
    /// Skip to next track.
    /// </summary>
    Skip,

    /// <summary>
    /// Seek to position.
    /// </summary>
    Seek
}
